CREATE TABLE IF NOT EXISTS thcdnaproddata.tpr.epic_source_query AS 
WITH ucl
AS (
	SELECT ucl.EPT_CSN
		,ucl.BILLING_PROVIDER_ID
	FROM thcdnaproddata.epic_ods.bap_clarity_ucl ucl
	GROUP BY ucl.EPT_CSN
		,ucl.BILLING_PROVIDER_ID
	)	,
Last_Enc
AS (
	SELECT 
		QO.OUTCOME_TYPE_C, 
		QI.PAT_ID AS PAT_ID, 
		QE.QUALITY_MEASURE_ID, 
		QI.QM_ENC_PROV_ID, 
		QI.REGISTRY_DATA_ID,
		ENC.CONTACT_DATE,
		ENC.PAT_ENC_CSN_ID as ENCOUNTER
		,CASE WHEN QO.OUTCOME_TYPE_C = 1 THEN 1 ELSE 0 END AS MEASURE_SATISFIED
		--,CASE WHEN QO.OUTCOME_TYPE_C = 7 THEN 1 ELSE 0 END AS EXCLUSION
		,CASE WHEN QO.OUTCOME_TYPE_C = 3 or  QO.OUTCOME_TYPE_C = 7  THEN 1 ELSE 0 END AS EXCLUSION
		/*********************Parul - Added QO.OUTCOME_TYPE_C = 3 in the case statement to exclude patients with status as exception from the Quality Dashboard******************************/
	FROM 
		thcdnaproddata.epic_ods.bap_qm_encounter QE
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_qm_gen_info QI 
			ON (QE.REGISTRY_DATA_ID = QI.REGISTRY_DATA_ID)
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_qm_enc_outcome QEO
			ON QE.REGISTRY_DATA_ID = QEO.REGISTRY_DATA_ID
				AND QE.LINE = QEO.GROUP_LINE
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_qm_outcomes QO 
			ON (QO.QM_ID = QE.QUALITY_MEASURE_ID)
				AND QO.OUTCOME = QEO.QM_OUTCOME
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_rdi_pat_csn RPC 
			ON RPC.REGISTRY_DATA_ID = QI.REGISTRY_DATA_ID
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_pat_enc ENC 
			ON RPC.PAT_CSN = ENC.PAT_ENC_CSN_ID
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_clarity_dep dep 
			ON enc.department_id = dep.department_id 
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_pat_enc_disp ped
			ON RPC.PAT_CSN = ped.PAT_ENC_CSN_ID
		LEFT OUTER JOIN UCL ucl ON RPC.PAT_CSN = ucl.EPT_CSN	
	WHERE 
		QI.PAT_DATE > PARSE_DATE('%m/%d/%Y','11/01/2017') AND QI.PAT_DATE < CURRENT_DATE('America/Chicago')
		AND QE.QUALITY_MEASURE_ID NOT IN (19278, 1007, 19275, 19274, 19337)
		AND (
			qi.QM_ENC_PROV_ID = ucl.BILLING_PROVIDER_ID
			OR QI.QM_ENC_PROV_ID = PED.LOS_AUTH_PROV_ID
			)
		AND QI.QM_TIN IS NOT NULL
		--AND QO.OUTCOME_TYPE_C IN  (1,7)
		AND ENC.DEPARTMENT_ID NOT IN (11101001,11101002,11101003,11101004,11101005,11101006,11101007,11101008,11101009,11101010,11101011
									,11101012,11101013,11101022,11101023,11101024,11101025,11101026,11101027,11101028,11101029,11101030
									,11101031,11101032,11101033,11101034,11101035,11101036,11101037,11101038,11101039,11102001,11102002
									,11102003,11103001,11103002,11104001,11104002,11105001,11106001,11107001,11108001,11109001,11110001
									,11111001,11112001,11113001,11113002,11114001,11115001,11116001,11117001,11118001,11119001,17101001
									,19101001,19101003,19101004,13101001,13101004,13101005,13103001,14101001,10001170,10173001,10157001)

	),

Last_Enc2
AS (
	SELECT
		Last_Enc.PAT_ID,
		Last_Enc.QM_ENC_PROV_ID,
		Last_Enc.QUALITY_MEASURE_ID,
		MAX(Last_Enc.REGISTRY_DATA_ID) REGISTRY_DATA_ID
	FROM
		Last_Enc
	GROUP BY
		Last_Enc.PAT_ID, Last_Enc.QM_ENC_PROV_ID, Last_Enc.QUALITY_MEASURE_ID
	),

All_Enc
AS (
	SELECT 
		QO.OUTCOME_TYPE_C, 
		QI.PAT_ID AS PAT_ID, 
		QE.QUALITY_MEASURE_ID, 
		QI.QM_ENC_PROV_ID, 
		QI.REGISTRY_DATA_ID,
		ENC.CONTACT_DATE,
		ENC.PAT_ENC_CSN_ID as ENCOUNTER
		,CASE WHEN QO.OUTCOME_TYPE_C = 1 THEN 1 ELSE 0 END AS MEASURE_SATISFIED
		--,CASE WHEN QO.OUTCOME_TYPE_C = 7 THEN 1 ELSE 0 END AS EXCLUSION
		,CASE WHEN QO.OUTCOME_TYPE_C = 3 or  QO.OUTCOME_TYPE_C = 7  THEN 1 ELSE 0 END AS EXCLUSION
		/*********************Parul - Added QO.OUTCOME_TYPE_C = 3 in the case statement to exclude patients with status as exception from the Quality Dashboard******************************/
	FROM 
		thcdnaproddata.epic_ods.bap_qm_encounter QE
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_qm_gen_info QI 
			ON (QE.REGISTRY_DATA_ID = QI.REGISTRY_DATA_ID)
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_qm_enc_outcome QEO
			ON QE.REGISTRY_DATA_ID = QEO.REGISTRY_DATA_ID
				AND QE.LINE = QEO.GROUP_LINE
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_qm_outcomes QO 
			ON (QO.QM_ID = QE.QUALITY_MEASURE_ID)
				AND QO.OUTCOME = QEO.QM_OUTCOME
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_rdi_pat_csn RPC 
			ON RPC.REGISTRY_DATA_ID = QI.REGISTRY_DATA_ID
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_pat_enc ENC 
			ON RPC.PAT_CSN = ENC.PAT_ENC_CSN_ID
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_clarity_dep dep 
			ON enc.department_id = dep.department_id 
		LEFT OUTER JOIN thcdnaproddata.epic_ods.bap_pat_enc_disp ped
			ON RPC.PAT_CSN = ped.PAT_ENC_CSN_ID
		LEFT OUTER JOIN UCL ucl ON RPC.PAT_CSN = ucl.EPT_CSN				
	WHERE 
		QI.PAT_DATE > PARSE_DATE('%m/%d/%Y','11/01/2017') AND QI.PAT_DATE < CURRENT_DATE('America/Chicago')
		AND QE.QUALITY_MEASURE_ID IN (19278, 1007, 19275, 19274, 19337)
		AND (
			qi.QM_ENC_PROV_ID = ucl.BILLING_PROVIDER_ID
			OR QI.QM_ENC_PROV_ID = PED.LOS_AUTH_PROV_ID
			)
		AND QI.QM_TIN IS NOT NULL
		--AND QO.OUTCOME_TYPE_C IN  (1,7)
		AND ENC.DEPARTMENT_ID NOT IN (11101001,11101002,11101003,11101004,11101005,11101006,11101007,11101008,11101009,11101010,11101011
									,11101012,11101013,11101022,11101023,11101024,11101025,11101026,11101027,11101028,11101029,11101030
									,11101031,11101032,11101033,11101034,11101035,11101036,11101037,11101038,11101039,11102001,11102002
									,11102003,11103001,11103002,11104001,11104002,11105001,11106001,11107001,11108001,11109001,11110001
									,11111001,11112001,11113001,11113002,11114001,11115001,11116001,11117001,11118001,11119001,17101001
									,19101001,19101003,19101004,13101001,13101004,13101005,13103001,14101001,10001170,10173001,10157001)
	)

SELECT 
	iid.IDENTITY_ID,
	Last_Enc.PAT_ID,
	pat.PAT_NAME, 
	Last_Enc2.QUALITY_MEASURE_ID, 
	qqm.RECORD_NAME,
	Last_Enc.QM_ENC_PROV_ID, 
	ser.PROV_NAME, 
	Last_Enc2.REGISTRY_DATA_ID,
	Last_Enc.CONTACT_DATE, 
	Last_Enc.ENCOUNTER, 
	max(MEASURE_SATISFIED) SATISFIED, 
	max(EXCLUSION) EXCLUDED
FROM 
	Last_Enc2
	INNER JOIN Last_Enc
		ON Last_Enc2.PAT_ID = Last_Enc.PAT_ID AND Last_Enc2.QUALITY_MEASURE_ID = Last_Enc.QUALITY_MEASURE_ID AND Last_Enc2.QM_ENC_PROV_ID = Last_Enc.QM_ENC_PROV_ID AND Last_Enc2.REGISTRY_DATA_ID = Last_Enc.REGISTRY_DATA_ID
	INNER JOIN thcdnaproddata.epic_ods.bap_clarity_ser ser 
		on Last_Enc.QM_ENC_PROV_ID=ser.PROV_ID
	INNER JOIN thcdnaproddata.epic_ods.bap_identity_id iid 
		ON Last_Enc.PAT_ID = iid.PAT_ID AND iid.IDENTITY_TYPE_ID = 42
	INNER JOIN thcdnaproddata.epic_ods.bap_patient pat 
		on Last_Enc.PAT_ID=pat.PAT_ID
	INNER JOIN thcdnaproddata.epic_ods.bap_qm_qual_measures qqm
		ON Last_Enc.QUALITY_MEASURE_ID = qqm.QM_ID
GROUP BY
	iid.IDENTITY_ID, 
	Last_Enc.PAT_ID, 
	Last_Enc2.QUALITY_MEASURE_ID,
	qqm.RECORD_NAME, 
	Last_Enc.QM_ENC_PROV_ID,   
	Last_Enc.ENCOUNTER, 
	ser.PROV_NAME,
	Last_Enc2.REGISTRY_DATA_ID,
	Last_Enc.CONTACT_DATE, 
	pat.PAT_NAME
	
UNION DISTINCT

SELECT 
	iid.IDENTITY_ID,
	All_Enc.PAT_ID,
	pat.PAT_NAME, 
	All_Enc.QUALITY_MEASURE_ID, 
	qqm.RECORD_NAME,
	All_Enc.QM_ENC_PROV_ID, 
	ser.PROV_NAME, 
	All_Enc.REGISTRY_DATA_ID,
	All_Enc.CONTACT_DATE, 
	All_Enc.ENCOUNTER, 
	max(MEASURE_SATISFIED) SATISFIED, 
	max(EXCLUSION) EXCLUDED
FROM 
	All_Enc
	INNER JOIN thcdnaproddata.epic_ods.bap_clarity_ser ser 
		on All_Enc.QM_ENC_PROV_ID=ser.PROV_ID
	INNER JOIN thcdnaproddata.epic_ods.bap_identity_id iid 
		ON All_Enc.PAT_ID = iid.PAT_ID AND iid.IDENTITY_TYPE_ID = 42
	INNER JOIN thcdnaproddata.epic_ods.bap_patient pat 
		on All_Enc.PAT_ID=pat.PAT_ID
	INNER JOIN thcdnaproddata.epic_ods.bap_qm_qual_measures qqm
		ON All_Enc.QUALITY_MEASURE_ID = qqm.QM_ID
GROUP BY
	iid.IDENTITY_ID, 
	All_Enc.PAT_ID, 
	All_Enc.QUALITY_MEASURE_ID,
	qqm.RECORD_NAME, 
	All_Enc.QM_ENC_PROV_ID,   
	All_Enc.ENCOUNTER, 
	ser.PROV_NAME,
	All_Enc.REGISTRY_DATA_ID,
	All_Enc.CONTACT_DATE, 
	pat.PAT_NAME
